import { describe, expect, it } from 'vitest';
import type { Line, TokenKind } from '../../src/ui/export/highlight';
import { highlightCode, highlightMarkdown, linesToText, tokenizeJson, tokenizeTs, toLines } from '../../src/ui/export/highlight';

/** Kind of the first token whose text is exactly `text`. */
function kindOf(lines: Line[], text: string): TokenKind | undefined {
  for (const line of lines) for (const tok of line) if (tok.t === text) return tok.k;
  return undefined;
}

const TS = `// Generated by kineReqLens
/** Order line. */
export interface OrderItem {
  sku: string;
  'unit-price'?: number;
  type: "physical" | "digital";
  createdAt: string; // date-time
}

export type GetOrdersResponse = OrderItem[] | null;
`;

const ZOD = `import { z } from 'zod';

export const OrderSchema = z.object({
  id: z.number().int(),
  email: z.string().email(),
});
export type Order = z.infer<typeof OrderSchema>;
`;

const JSON_SCHEMA = `{
  "$schema": "https://json-schema.org/draft/2020-12/schema",
  "type": "object",
  "required": ["id"],
  "properties": { "id": { "type": "integer", "examples": [-12, 3.5e3] }, "ok": true, "x": null }
}`;

describe('highlightCode', () => {
  it.each([
    ['ts', TS],
    ['ts', ZOD],
    ['json', JSON_SCHEMA],
    ['plain', 'a\n\nb'],
    ['ts', ''],
    ['ts', 'const s = "unterminated\nnext line'],
    ['ts', '/* block\n comment */ type A = 1;'],
    ['json', '{"a": "b\\"c", "d": [1, -2]}'],
  ] as const)('round-trips the text exactly (%s)', (lang, src) => {
    const lines = highlightCode(src, lang);
    expect(linesToText(lines)).toBe(src);
    expect(lines.length).toBe(src.split('\n').length);
    for (const line of lines) for (const tok of line) expect(tok.t).not.toContain('\n');
  });

  it('classifies TypeScript declarations', () => {
    const lines = highlightCode(TS, 'ts');
    expect(kindOf(lines, '// Generated by kineReqLens')).toBe('com');
    expect(kindOf(lines, '/** Order line. */')).toBe('com');
    expect(kindOf(lines, 'export')).toBe('kw');
    expect(kindOf(lines, 'interface')).toBe('kw');
    expect(kindOf(lines, 'OrderItem')).toBe('type');
    expect(kindOf(lines, 'sku')).toBe('key');
    expect(kindOf(lines, "'unit-price'")).toBe('key');
    expect(kindOf(lines, 'string')).toBe('type');
    expect(kindOf(lines, '"physical"')).toBe('str');
    expect(kindOf(lines, 'null')).toBe('lit');
    // A property named like a keyword is still a key.
    expect(kindOf(lines, 'type')).toBe('key');
  });

  it('classifies Zod output', () => {
    const lines = highlightCode(ZOD, 'ts');
    expect(kindOf(lines, 'import')).toBe('kw');
    expect(kindOf(lines, "'zod'")).toBe('str');
    expect(kindOf(lines, 'OrderSchema')).toBe('type');
    expect(kindOf(lines, 'object')).toBe('fn');
    expect(kindOf(lines, 'int')).toBe('fn');
    expect(kindOf(lines, 'id')).toBe('key');
    expect(kindOf(lines, 'typeof')).toBe('kw');
  });

  it('classifies JSON keys, strings, numbers and literals', () => {
    const tokens = tokenizeJson(JSON_SCHEMA);
    const kind = (t: string) => tokens.find((x) => x.t === t)?.k;
    expect(kind('"$schema"')).toBe('key');
    expect(kind('"https://json-schema.org/draft/2020-12/schema"')).toBe('str');
    // "id" is a value inside `required` and a key inside `properties`.
    expect(tokens.filter((x) => x.t === '"id"').map((x) => x.k)).toEqual(['str', 'key']);
    expect(kind('-12')).toBe('num');
    expect(kind('3.5e3')).toBe('num');
    expect(kind('true')).toBe('lit');
    expect(kind('null')).toBe('lit');
  });

  it('does not colour digits inside identifiers', () => {
    const tokens = tokenizeTs('type V2 = { a1: number };');
    expect(tokens.some((t) => t.k === 'num')).toBe(false);
  });

  it('merges adjacent plain text into one token', () => {
    const tokens = tokenizeTs('a = { };');
    expect(tokens.filter((t) => t.k === '').length).toBeLessThanOrEqual(2);
  });

  it('splits multi-line tokens at line breaks', () => {
    const lines = toLines([{ k: 'com', t: '/* a\nb */' }, { k: '', t: ' x' }]);
    expect(lines).toEqual([[{ k: 'com', t: '/* a' }], [{ k: 'com', t: 'b */' }, { k: '', t: ' x' }]]);
  });
});

describe('highlightMarkdown', () => {
  const PROMPT = [
    '<!-- Generated by kineReqLens from https://app.test at 2026-01-01T00:00:00.000Z -->',
    '# Task',
    'Add a client for `POST /api/orders`.',
    '',
    '```ts',
    'export interface CreateOrderRequestBody {',
    '  sku: string;',
    '}',
    '```',
    '```json',
    '{ "sku": "A-1" }',
    '```',
    '- [ ] Done',
    '```graphql',
    'query GetUser { user { id } }',
  ].join('\n');

  it('round-trips the prompt exactly, one output line per input line', () => {
    const lines = highlightMarkdown(PROMPT);
    expect(linesToText(lines)).toBe(PROMPT);
    expect(lines.length).toBe(PROMPT.split('\n').length);
  });

  it('classifies headings, comments, inline code, fences and fenced code', () => {
    const lines = highlightMarkdown(PROMPT);
    expect(lines[0]).toEqual([{ k: 'com', t: PROMPT.split('\n')[0] }]);
    expect(lines[1]).toEqual([{ k: 'h', t: '# Task' }]);
    expect(kindOf(lines, '`POST /api/orders`')).toBe('code');
    expect(kindOf(lines, '```ts')).toBe('fence');
    expect(kindOf(lines, 'interface')).toBe('kw');
    expect(kindOf(lines, '"sku"')).toBe('key');
    // GraphQL is not coloured (plain), and an unterminated fence runs to the end.
    expect(kindOf(lines, 'query GetUser { user { id } }')).toBe('');
  });

  it('handles empty fenced blocks', () => {
    const src = '```\n```';
    expect(linesToText(highlightMarkdown(src))).toBe(src);
  });
});
