function answer(req: Extract<HostToExtension, { t: 'req' }>): { ok: true; result: unknown } | { ok: false; error: string } {
  const params = (req.params ?? {}) as Record<string, unknown>;
  switch (req.method as BridgeMethod) {
    case 'status':
      return { ok: true, result: STATUS };
    case 'listRequests':
      return { ok: true, result: params.query === 'malformed' ? { tabId: 7 } : LIST };
    case 'getRequest':
      return params.id === 'missing' ? { ok: false, error: 'No request with id "missing" in tab 7' } : { ok: true, result: DETAIL };
    case 'getTypes':
      return { ok: true, result: TYPES };
    case 'getPrompt':
      return { ok: true, result: { prompt: PROMPT_TEXT, target: params.target ?? 'client' } };
    case 'sendRequest':
      return params.id === 'blocked'
        ? { ok: false, error: 'Sending is off: enable "Allow Claude to send requests" in kineReqLens Settings → Claude Code.' }
        : { ok: true, result: { ...RUN, responseHeaders: [['x-trace', 'abc']] } };
    case 'control': {
      const args = (params.args ?? {}) as Record<string, unknown>;
      if (params.tool === 'overlay' && params.action === 'close') return { ok: false, error: 'Controlling kineReqLens is turned off.' };
      if (params.tool === 'inspect' && params.action === 'activity') return { ok: false, error: 'Unknown method "control"' };
      if (params.tool === 'screenshot') {
        return {
          ok: true,
          result: { text: `shot of ${String(args.text)}`, images: [{ data: PNG_1PX, mimeType: 'image/png', width: 1, height: 1 }, { data: 'A'.repeat(7_000_000), mimeType: 'image/png' }] },
        };
      }
      if (params.tool === 'requests' && params.action === 'resend') return { ok: true, result: { text: 'Re-sent:', run: { ...RUN, origin: 'claude' } } };
      return { ok: true, result: { text: `${String(params.tool)}.${String(params.action)} ok` } };
    }
    default:
      return { ok: false, error: `unexpected ${req.method}` };
  }
}

interface Spawned {
  client: Client;
  notifications: Notification[];
  errors: Error[];
  stderr: () => string;
}

async function spawnServer(home: string, cwd: string): Promise<Spawned> {
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [buildBundle(), 'serve'],
    env: { REQLENS_HOME: home },
    cwd,
    stderr: 'pipe',
  });
  let stderr = '';
  transport.stderr?.on('data', (chunk: Buffer) => {
    stderr += chunk.toString();
  });
  const client = new Client({ name: 'reqlens-test', version: '1.0.0' });
  const notifications: Notification[] = [];
  const errors: Error[] = [];
  client.fallbackNotificationHandler = async (notification) => {
    notifications.push(notification);
  };
  client.onerror = (error) => errors.push(error);
  await client.connect(transport);
  return { client, notifications, errors, stderr: () => stderr };
}

type TextResult = { content: Array<{ type: string; text?: string }>; isError?: boolean };

async function callText(client: Client, name: string, args: Record<string, unknown> = {}): Promise<{ text: string; isError: boolean }> {
  const result = (await client.callTool({ name, arguments: args })) as TextResult;
  expect(result.content).toHaveLength(1);
  expect(result.content[0]?.type).toBe('text');
  return { text: result.content[0]?.text ?? '', isError: result.isError === true };
}


