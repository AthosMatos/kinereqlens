describe('reqlens-mcp serve (not connected)', () => {
  let root: string;
  let home: string;
  let server: Spawned;

  beforeAll(async () => {
    buildBundle();
    root = tempDir();
    home = path.join(root, 'home');
    server = await spawnServer(home, root);
  }, 30_000);

  afterAll(async () => {
    await server?.client.close();
    removeDir(root);
  });

  it('explains how to install when the native host is missing', async () => {
    const result = await callText(server.client, 'list_requests');
    expect(result.isError).toBe(true);
    expect(result.text).toContain('the browser bridge (native messaging host) is not installed');
    expect(result.text).toContain('npm run mcp:install -- --extension-id <id>');
    expect(result.text).toContain('Open Edge → kineReqLens overlay → Settings → Claude Code → Enable');
    const status = await callText(server.client, 'status');
    expect(status.isError).toBe(false);
    expect(status.text).toContain('not installed');
    expect(status.text).toContain('This session:');
  });

  it('tells the user to enable the bridge when installed but no hub runs', async () => {
    fs.mkdirSync(home, { recursive: true });
    fs.writeFileSync(launcherPath(home), '#!/bin/sh\n');
    const result = await callText(server.client, 'get_request', { id: 'selected' });
    expect(result.isError).toBe(true);
    expect(result.text).toContain('the browser bridge is not running');
    expect(result.text).toContain('Open Edge → kineReqLens overlay → Settings → Claude Code → Enable');
    expect(result.text).toMatch(/reqlens-mcp\.mjs" doctor/);
  });

  it('connects as soon as a hub appears, and reports the loss when it goes away', async () => {
    const { hub, ext } = await startHub(home);
    ext.sendHello();
    ext.responder = answer;
    await waitFor(() => ext.of('sessions').at(-1)?.sessions.length === 1, 5000, 'session after hub start');
    expect((await callText(server.client, 'status')).text).toContain('kineReqLens: connected');
    ext.disconnect();
    await hub.closed;
    const after = await callText(server.client, 'list_requests');
    expect(after.isError).toBe(true);
    expect(after.text).toContain('the browser bridge is not running');
  });
});
