import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { runChecks } from '../doctor';
import { EXTENSION_ID_UNPACKED } from '../../../src/shared/constants';
import {
  DEFAULT_EXTENSION_ID,
  type InstallContext,
  InstallError,
  MISSING_ID_MESSAGE,
  buildManifest,
  install,
  launcherScript,
  normalizeExtensionId,
  parseLauncher,
  readManifestIds,
  selectChannels,
  stableNodePath,
  uninstall,
} from '../install';
import { browserChannels, launcherPath } from '../paths';
import { removeDir, tempDir } from './helpers';

const ID_A = 'abcdefghijklmnopabcdefghijklmnop';
const ID_B = 'ponmlkjihgfedcbaponmlkjihgfedcba';

let root: string;
let lines: string[];

beforeEach(() => {
  root = tempDir();
  lines = [];
});

afterEach(() => removeDir(root));

/** An install context confined to the temp root (never the real home or browser profiles). */
function context(extra: Partial<InstallContext> = {}): InstallContext {
  const script = path.join(root, 'dist', 'reqlens-mcp.mjs');
  fs.mkdirSync(path.dirname(script), { recursive: true });
  fs.writeFileSync(script, '// bundle');
  return {
    home: path.join(root, 'rlhome'),
    homedir: path.join(root, 'user'),
    platform: 'darwin',
    env: {},
    nodePath: process.execPath,
    scriptPath: script,
    out: (line) => lines.push(line),
    manifestDir: path.join(root, 'profile', 'NativeMessagingHosts'),
    ...extra,
  };
}

const manifestFile = (ctx: InstallContext): string => path.join(ctx.manifestDir ?? '', 'com.reqlens.bridge.json');

describe('extension ids', () => {
  it('allows the unpacked build fixed id by default (a valid id)', () => {
    expect(DEFAULT_EXTENSION_ID).toBe(EXTENSION_ID_UNPACKED);
    expect(normalizeExtensionId(DEFAULT_EXTENSION_ID)).toBe(DEFAULT_EXTENSION_ID);
  });

  it('accepts bare ids and chrome-extension origins, rejects anything else', () => {
    expect(normalizeExtensionId(ID_A)).toBe(ID_A);
    expect(normalizeExtensionId(` chrome-extension://${ID_A.toUpperCase()}/ `)).toBe(ID_A);
    expect(normalizeExtensionId(`chrome-extension://${ID_A}`)).toBe(ID_A);
    expect(normalizeExtensionId('abcdefghijklmnopabcdefghijklmnoz')).toBeNull();
    expect(normalizeExtensionId('short')).toBeNull();
    expect(normalizeExtensionId(`${ID_A}x`)).toBeNull();
  });
});

describe('install --manifest-dir', () => {
  it('writes the manifest and an executable launcher that bakes REQLENS_HOME', () => {
    const ctx = context();
    const result = install({ ...ctx, extensionIds: [ID_A] });
    const launcher = launcherPath(ctx.home, 'darwin');
    expect(result).toEqual({ launcher, manifests: [manifestFile(ctx)], registryKeys: [], extensionIds: [ID_A] });
    expect(JSON.parse(fs.readFileSync(manifestFile(ctx), 'utf8'))).toEqual({
      name: 'com.reqlens.bridge',
      description: 'kineReqLens bridge to Claude Code (reqlens-mcp native-host)',
      path: launcher,
      type: 'stdio',
      allowed_origins: [`chrome-extension://${ID_A}/`],
    });
    expect(fs.readFileSync(launcher, 'utf8')).toBe(
      [
        '#!/bin/sh',
        '# Generated by reqlens-mcp install: native messaging host for com.reqlens.bridge',
        `REQLENS_HOME="${ctx.home}"`,
        'export REQLENS_HOME',
        `exec "${process.execPath}" "${ctx.scriptPath}" native-host "$@"`,
        '',
      ].join('\n'),
    );
    expect(fs.statSync(launcher).mode & 0o777).toBe(0o755);
    expect(fs.statSync(ctx.home).mode & 0o777).toBe(0o700);
    expect(lines.join('\n')).toContain(`claude mcp add --scope user reqlens -- "${process.execPath}" "${ctx.scriptPath}"`);
    expect(lines.join('\n')).toContain('claude --dangerously-load-development-channels server:reqlens');
    // Never touched the (temp) user home.
    expect(fs.existsSync(ctx.homedir)).toBe(false);
  });

  it('is idempotent', () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    const before = fs.statSync(manifestFile(ctx)).mtimeMs;
    const launcherBefore = fs.readFileSync(launcherPath(ctx.home, 'darwin'), 'utf8');
    lines = [];
    install({ ...ctx, extensionIds: [ID_A] });
    expect(lines.filter((line) => line.startsWith('Up to date'))).toHaveLength(2);
    expect(fs.statSync(manifestFile(ctx)).mtimeMs).toBe(before);
    expect(fs.readFileSync(launcherPath(ctx.home, 'darwin'), 'utf8')).toBe(launcherBefore);
    expect(readManifestIds(manifestFile(ctx))).toEqual([ID_A]);
  });

  it('keeps the ids of an existing manifest and adds new ones', () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    expect(install({ ...ctx, extensionIds: [] }).extensionIds).toEqual([ID_A]);
    expect(install({ ...ctx, extensionIds: [ID_B, ID_A] }).extensionIds).toEqual([ID_A, ID_B]);
    expect(readManifestIds(manifestFile(ctx))).toEqual([ID_A, ID_B]);
  });

  it('fails with instructions when there is no id at all, and on invalid ids', () => {
    const ctx = context();
    expect(() => install({ ...ctx, extensionIds: [] })).toThrow(InstallError);
    expect(() => install({ ...ctx, extensionIds: [] })).toThrow(MISSING_ID_MESSAGE);
    expect(MISSING_ID_MESSAGE).toContain('npm run mcp:install -- --extension-id <id>');
    expect(() => install({ ...ctx, extensionIds: ['nope'] })).toThrow(/Invalid extension id "nope"/);
    expect(fs.existsSync(ctx.home)).toBe(false);
  });

  it('refuses a REQLENS_HOME whose socket path would be too long', () => {
    const ctx = context({ home: path.join(root, 'h'.repeat(110)) });
    expect(() => install({ ...ctx, extensionIds: [ID_A] })).toThrow(/shorter REQLENS_HOME/);
  });

  it('uninstalls the manifest and the launcher', () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    lines = [];
    const result = uninstall(ctx);
    expect(result.removed.sort()).toEqual([launcherPath(ctx.home, 'darwin'), manifestFile(ctx)].sort());
    expect(fs.existsSync(manifestFile(ctx))).toBe(false);
    expect(fs.existsSync(launcherPath(ctx.home, 'darwin'))).toBe(false);
    lines = [];
    expect(uninstall(ctx).removed).toEqual([]);
    expect(lines).toContain('Nothing to remove.');
  });
});

describe('launcher script', () => {
  it('quotes paths with spaces, quotes, $ and backticks so sh runs them verbatim', () => {
    const weird = path.join(root, 'we "ird" $HOME `x` dir');
    fs.mkdirSync(weird, { recursive: true });
    const script = path.join(weird, 'probe.mjs');
    fs.writeFileSync(script, 'console.log(JSON.stringify({ home: process.env.REQLENS_HOME, argv: process.argv.slice(2) }));\n');
    const home = path.join(weird, 'home');
    const content = launcherScript(process.execPath, script, home, 'darwin');
    const launcher = path.join(root, 'native-host');
    fs.writeFileSync(launcher, content, { mode: 0o755 });
    const output = execFileSync(launcher, [`chrome-extension://${ID_A}/`], { encoding: 'utf8', env: { PATH: '/usr/bin:/bin' } });
    expect(JSON.parse(output)).toEqual({ home, argv: ['native-host', `chrome-extension://${ID_A}/`] });
    expect(parseLauncher(content)).toEqual({ nodePath: process.execPath, scriptPath: script, home });
  });

  it('writes a .cmd launcher on Windows', () => {
    const content = launcherScript('C:\\node\\node.exe', 'C:\\rl\\reqlens-mcp.mjs', 'C:\\Users\\me\\.reqlens', 'win32');
    expect(content).toBe(
      '@echo off\r\nrem Generated by reqlens-mcp install: native messaging host for com.reqlens.bridge\r\nset "REQLENS_HOME=C:\\Users\\me\\.reqlens"\r\n"C:\\node\\node.exe" "C:\\rl\\reqlens-mcp.mjs" native-host %*\r\n',
    );
    expect(parseLauncher(content)).toEqual({ nodePath: 'C:\\node\\node.exe', scriptPath: 'C:\\rl\\reqlens-mcp.mjs', home: 'C:\\Users\\me\\.reqlens' });
    expect(parseLauncher('#!/bin/sh\necho hi\n')).toBeNull();
  });

  it('prefers a stable PATH entry that resolves to the running node', () => {
    const bin = path.join(root, 'bin');
    fs.mkdirSync(bin);
    fs.symlinkSync(process.execPath, path.join(bin, 'node'));
    expect(stableNodePath(process.execPath, `/nonexistent:${bin}`, 'darwin')).toBe(path.join(bin, 'node'));
    expect(stableNodePath(process.execPath, '/nonexistent', 'darwin')).toBe(process.execPath);
    expect(stableNodePath(process.execPath, undefined, 'darwin')).toBe(process.execPath);
  });
});

describe('browser selection', () => {
  const mkProfile = (homedir: string, ...parts: string[]): void => {
    fs.mkdirSync(path.join(homedir, ...parts), { recursive: true });
  };

  it('knows the per-OS NativeMessagingHosts directories', () => {
    const mac = browserChannels('darwin', '/Users/me', {});
    expect(mac.find((ch) => ch.name === 'Microsoft Edge')?.manifestDir).toBe('/Users/me/Library/Application Support/Microsoft Edge/NativeMessagingHosts');
    expect(mac.find((ch) => ch.name === 'Google Chrome')?.manifestDir).toBe('/Users/me/Library/Application Support/Google/Chrome/NativeMessagingHosts');
    expect(mac.find((ch) => ch.family === 'brave')?.manifestDir).toBe('/Users/me/Library/Application Support/BraveSoftware/Brave-Browser/NativeMessagingHosts');
    expect(mac.map((ch) => ch.name)).toEqual(
      expect.arrayContaining(['Microsoft Edge Beta', 'Microsoft Edge Dev', 'Microsoft Edge Canary', 'Chromium']),
    );
    const linux = browserChannels('linux', '/home/me', {});
    expect(linux.find((ch) => ch.name === 'Microsoft Edge')?.manifestDir).toBe('/home/me/.config/microsoft-edge/NativeMessagingHosts');
    expect(linux.find((ch) => ch.name === 'Google Chrome')?.manifestDir).toBe('/home/me/.config/google-chrome/NativeMessagingHosts');
    expect(browserChannels('linux', '/home/me', { XDG_CONFIG_HOME: '/xdg' })[0]?.manifestDir).toBe('/xdg/microsoft-edge/NativeMessagingHosts');
    const win = browserChannels('win32', 'C:\\Users\\me', {});
    expect(win.map((ch) => ch.registryKey)).toEqual([
      'HKCU\\Software\\Microsoft\\Edge\\NativeMessagingHosts\\com.reqlens.bridge',
      'HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\com.reqlens.bridge',
      'HKCU\\Software\\Chromium\\NativeMessagingHosts\\com.reqlens.bridge',
      'HKCU\\Software\\BraveSoftware\\Brave-Browser\\NativeMessagingHosts\\com.reqlens.bridge',
    ]);
  });

  it('picks installed browsers by default, the main channel of named ones, Edge as a fallback', () => {
    const channels = browserChannels('darwin', '/u', {});
    const installed = new Set(['/u/Library/Application Support/Microsoft Edge Beta', '/u/Library/Application Support/Google/Chrome']);
    const exists = (dir: string): boolean => installed.has(dir);
    expect(selectChannels(channels, [], exists).map((ch) => ch.name)).toEqual(['Microsoft Edge Beta', 'Google Chrome']);
    expect(selectChannels(channels, ['brave'], exists).map((ch) => ch.name)).toEqual(['Brave']);
    expect(selectChannels(channels, ['edge'], exists).map((ch) => ch.name)).toEqual(['Microsoft Edge', 'Microsoft Edge Beta']);
    expect(selectChannels(channels, ['all'], exists).map((ch) => ch.name)).toEqual([
      'Microsoft Edge',
      'Microsoft Edge Beta',
      'Google Chrome',
      'Chromium',
      'Brave',
    ]);
    expect(selectChannels(channels, [], () => false).map((ch) => ch.name)).toEqual(['Microsoft Edge']);
  });

  it('writes into each installed browser profile under the (temp) user home and uninstalls from all', () => {
    const ctx = context({ manifestDir: undefined });
    delete ctx.manifestDir;
    mkProfile(ctx.homedir, 'Library', 'Application Support', 'Microsoft Edge');
    mkProfile(ctx.homedir, 'Library', 'Application Support', 'Google', 'Chrome');
    const result = install({ ...ctx, extensionIds: [ID_A] });
    const support = path.join(ctx.homedir, 'Library', 'Application Support');
    expect(result.manifests).toEqual([
      path.join(support, 'Microsoft Edge', 'NativeMessagingHosts', 'com.reqlens.bridge.json'),
      path.join(support, 'Google', 'Chrome', 'NativeMessagingHosts', 'com.reqlens.bridge.json'),
    ]);
    expect(fs.existsSync(path.join(support, 'BraveSoftware'))).toBe(false);
    // A later install for one browser keeps the ids the others allow.
    expect(install({ ...ctx, browsers: ['brave'], extensionIds: [] }).extensionIds).toEqual([ID_A]);
    expect(uninstall(ctx).removed).toHaveLength(4);
  });

  it('uses the registry on Windows (manifest kept in REQLENS_HOME)', () => {
    const calls: string[][] = [];
    const ctx = context({ platform: 'win32', env: { LOCALAPPDATA: 'C:\\nowhere' }, runReg: (args) => (calls.push(args), '') });
    delete ctx.manifestDir;
    const result = install({ ...ctx, browsers: ['edge'], extensionIds: [ID_A] });
    const manifest = path.join(ctx.home, 'com.reqlens.bridge.json');
    expect(result.manifests).toEqual([manifest]);
    expect(result.registryKeys).toEqual(['HKCU\\Software\\Microsoft\\Edge\\NativeMessagingHosts\\com.reqlens.bridge']);
    expect(calls).toEqual([['add', 'HKCU\\Software\\Microsoft\\Edge\\NativeMessagingHosts\\com.reqlens.bridge', '/ve', '/t', 'REG_SZ', '/d', manifest, '/f']]);
    expect(JSON.parse(fs.readFileSync(manifest, 'utf8')).path).toBe(path.join(ctx.home, 'native-host.cmd'));
    calls.length = 0;
    uninstall(ctx);
    expect(calls.map((args) => args[0])).toEqual(['delete', 'delete', 'delete', 'delete']);
    expect(fs.existsSync(manifest)).toBe(false);
  });
});

describe('doctor', () => {
  const probe = (state: 'live' | 'stale' | 'missing') => () => Promise.resolve(state);

  it('passes after an install (hub not running is only a warning)', async () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    const checks = await runChecks({ ...ctx, probe: probe('missing') });
    expect(checks.filter((check) => check.status === 'fail')).toEqual([]);
    expect(checks.at(-1)).toMatchObject({ status: 'warn', title: expect.stringContaining('Hub not running') });
    expect(checks.map((check) => check.title)).toContain(`Allowed extension ids: ${ID_A}`);
    const live = await runChecks({ ...ctx, probe: probe('live') });
    expect(live.at(-1)).toMatchObject({ status: 'ok', title: expect.stringContaining('Hub running') });
  });

  it('flags a missing install with the fix', async () => {
    const ctx = context();
    const checks = await runChecks({ ...ctx, probe: probe('missing') });
    const failed = checks.filter((check) => check.status === 'fail');
    expect(failed.map((check) => check.title)).toEqual([
      expect.stringContaining('does not exist'),
      expect.stringContaining('Launcher missing'),
      expect.stringContaining('no manifest'),
    ]);
    expect(failed[1]?.fix).toContain('re-run the installer: npm run mcp:install');
  });

  it('warns when the unpacked build fixed id is not allowed (installs made before the manifest key)', async () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    const before = await runChecks({ ...ctx, probe: probe('missing') });
    const warning = before.find((check) => check.title.includes(DEFAULT_EXTENSION_ID));
    expect(warning).toMatchObject({ status: 'warn', title: expect.stringContaining('is not allowed') });
    expect(warning?.fix).toContain('npm run mcp:install');
    expect(before.filter((check) => check.status === 'fail')).toEqual([]);
    install({ ...ctx, extensionIds: [DEFAULT_EXTENSION_ID] });
    const after = await runChecks({ ...ctx, probe: probe('missing') });
    expect(after.map((check) => check.title)).toContain(`Allowed extension ids: ${ID_A}, ${DEFAULT_EXTENSION_ID}`);
    expect(after.some((check) => check.title.includes('is not allowed'))).toBe(false);
  });

  it('flags a broken launcher target, a foreign manifest path and an old node', async () => {
    const ctx = context();
    install({ ...ctx, extensionIds: [ID_A] });
    fs.rmSync(ctx.scriptPath);
    const manifest = JSON.parse(fs.readFileSync(manifestFile(ctx), 'utf8'));
    fs.writeFileSync(manifestFile(ctx), JSON.stringify({ ...manifest, path: '/elsewhere/host', allowed_origins: [] }));
    const checks = await runChecks({ ...ctx, nodeVersion: 'v18.19.0', probe: probe('stale') });
    const titles = checks.filter((check) => check.status === 'fail').map((check) => `${check.title} ${check.detail ?? ''}`);
    expect(titles).toEqual([
      expect.stringContaining('Node v18.19.0 is too old'),
      expect.stringContaining('Script missing'),
      expect.stringContaining('missing script'),
      expect.stringMatching(/path is \/elsewhere\/host.*no valid extension id/),
    ]);
    expect(checks.at(-1)?.title).toContain('stale socket');
  });

  it('builds a manifest with one origin per id', () => {
    expect(buildManifest('/x/native-host', [ID_A, ID_B]).allowed_origins).toEqual([`chrome-extension://${ID_A}/`, `chrome-extension://${ID_B}/`]);
  });
});
