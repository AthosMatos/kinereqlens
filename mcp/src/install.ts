// `reqlens-mcp install | uninstall`: writes the native host launcher ($REQLENS_HOME/native-host, which bakes
// in REQLENS_HOME and absolute node / script paths) and the native messaging manifest for each browser
// (macOS / Linux: user-level NativeMessagingHosts dirs; Windows: manifest in $REQLENS_HOME + HKCU key).
// Idempotent; ids already allowed by existing manifests are kept.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { NATIVE_HOST_NAME } from '../../src/shared/claude-protocol';
import { EXTENSION_ID_UNPACKED } from '../../src/shared/constants';
import {
  BROWSER_FAMILIES,
  type BrowserChannel,
  type BrowserFamily,
  browserChannels,
  homeManifestPath,
  hubSocketPath,
  launcherPath,
  manifestFileName,
  socketPathProblem,
} from './paths';

export type BrowserChoice = BrowserFamily | 'all';

/** The JSON file browsers read to find and authorize the native host. */
export interface NativeHostManifest {
  name: string;
  description: string;
  path: string;
  type: 'stdio';
  allowed_origins: string[];
}

/** Runs `reg.exe` with the given arguments (Windows only; injectable for tests). Throws on failure. */
export type RegRunner = (args: string[]) => string;

export interface InstallContext {
  /** $REQLENS_HOME. */
  home: string;
  /** Only this NativeMessagingHosts directory (E2E temp profiles); no browser dirs, no registry. */
  manifestDir?: string;
  browsers?: BrowserChoice[];
  /** The user's home directory (browser profile locations are under it). */
  homedir: string;
  platform: NodeJS.Platform;
  env: NodeJS.ProcessEnv;
  /** Absolute node binary and reqlens-mcp.mjs paths baked into the launcher. */
  nodePath: string;
  scriptPath: string;
  out: (line: string) => void;
  runReg?: RegRunner;
}

export interface InstallOptions extends InstallContext {
  extensionIds: string[];
}

export interface InstallResult {
  launcher: string;
  /** Manifest files written or already up to date. */
  manifests: string[];
  /** Windows registry keys set. */
  registryKeys: string[];
  extensionIds: string[];
}

/** A user-facing failure (bad arguments, nothing to authorize); the CLI prints the message and exits 1. */
export class InstallError extends Error {}

export const MISSING_ID_MESSAGE = [
  'No extension id given and no existing manifest to take one from.',
  'Find the id in the browser: kineReqLens overlay → Settings → Claude Code (or edge://extensions with developer mode on),',
  'then run:  npm run mcp:install -- --extension-id <id>',
].join('\n');

/**
 * Allowed by every `reqlens-mcp install`: the unpacked build's id, fixed by the "key" in static/manifest.json (the
 * same on every machine). `--extension-id` adds more (e.g. a store build's id).
 */
export const DEFAULT_EXTENSION_ID = EXTENSION_ID_UNPACKED;

const EXTENSION_ID = /^[a-p]{32}$/;

/** Accepts a bare id or a `chrome-extension://<id>/` origin; null when invalid. */
export function normalizeExtensionId(raw: string): string | null {
  const text = raw.trim().toLowerCase();
  const match = /^chrome-extension:\/\/([^/]+)\/?$/.exec(text);
  const id = match?.[1] ?? text;
  return EXTENSION_ID.test(id) ? id : null;
}

export function extensionOrigin(id: string): string {
  return `chrome-extension://${id}/`;
}

export function buildManifest(launcher: string, extensionIds: string[]): NativeHostManifest {
  return {
    name: NATIVE_HOST_NAME,
    description: 'kineReqLens bridge to Claude Code (reqlens-mcp native-host)',
    path: launcher,
    type: 'stdio',
    allowed_origins: extensionIds.map(extensionOrigin),
  };
}

/** `"value"` for sh: backslash-escapes the characters that stay special inside double quotes. */
function shQuote(value: string): string {
  return `"${value.replace(/(["\\$`])/g, '\\$1')}"`;
}

/** Launcher script content (sh on macOS / Linux, cmd on Windows). Extra args (the caller origin) pass through. */
export function launcherScript(nodePath: string, scriptPath: string, home: string, platform: NodeJS.Platform): string {
  if (platform === 'win32') {
    return [
      '@echo off',
      'rem Generated by reqlens-mcp install: native messaging host for com.reqlens.bridge',
      `set "REQLENS_HOME=${home}"`,
      `"${nodePath}" "${scriptPath}" native-host %*`,
      '',
    ].join('\r\n');
  }
  return [
    '#!/bin/sh',
    '# Generated by reqlens-mcp install: native messaging host for com.reqlens.bridge',
    `REQLENS_HOME=${shQuote(home)}`,
    'export REQLENS_HOME',
    `exec ${shQuote(nodePath)} ${shQuote(scriptPath)} native-host "$@"`,
    '',
  ].join('\n');
}

/** Paths a launcher script points at (for doctor), or null when it is not one of ours. */
export function parseLauncher(content: string): { nodePath: string; scriptPath: string; home: string | null } | null {
  const unescape = (value: string): string => value.replace(/\\(["\\$`])/g, '$1');
  const sh = /^exec "((?:[^"\\]|\\.)*)" "((?:[^"\\]|\\.)*)" native-host/m.exec(content);
  if (sh) {
    const home = /^REQLENS_HOME="((?:[^"\\]|\\.)*)"/m.exec(content);
    return { nodePath: unescape(sh[1] ?? ''), scriptPath: unescape(sh[2] ?? ''), home: home ? unescape(home[1] ?? '') : null };
  }
  const cmd = /^"([^"]*)" "([^"]*)" native-host/m.exec(content);
  if (cmd) {
    const home = /^set "REQLENS_HOME=([^"]*)"/m.exec(content);
    return { nodePath: cmd[1] ?? '', scriptPath: cmd[2] ?? '', home: home?.[1] ?? null };
  }
  return null;
}

/**
 * The node binary to bake into the launcher: a PATH entry that resolves to the running binary when there is
 * one (e.g. Homebrew's /opt/homebrew/bin/node survives upgrades, its versioned Cellar path does not), else
 * `execPath`. Always absolute: browsers start native hosts without the shell's PATH.
 */
export function stableNodePath(execPath: string, envPath: string | undefined, platform: NodeJS.Platform): string {
  const real = (file: string): string | null => {
    try {
      return fs.realpathSync(file);
    } catch {
      return null;
    }
  };
  const target = real(execPath);
  if (!target || !envPath) return execPath;
  const names = platform === 'win32' ? ['node.exe'] : ['node'];
  for (const dir of envPath.split(path.delimiter)) {
    if (!dir || !path.isAbsolute(dir)) continue;
    for (const name of names) {
      const candidate = path.join(dir, name);
      if (real(candidate) === target) return candidate;
    }
  }
  return execPath;
}

/** Ids allowed by a manifest file (empty when missing or unreadable). */
export function readManifestIds(file: string): string[] {
  try {
    const manifest = JSON.parse(fs.readFileSync(file, 'utf8')) as Partial<NativeHostManifest>;
    if (!Array.isArray(manifest.allowed_origins)) return [];
    return manifest.allowed_origins
      .map((origin) => (typeof origin === 'string' ? normalizeExtensionId(origin) : null))
      .filter((id): id is string => id !== null);
  } catch {
    return [];
  }
}

/**
 * Browser channels to write. No --browser: the installed ones (profile dir exists), Edge if none is.
 * Named families (or `all`): their main channel always, plus their other installed channels.
 */
export function selectChannels(
  channels: BrowserChannel[],
  browsers: BrowserChoice[] | undefined,
  exists: (dir: string) => boolean,
): BrowserChannel[] {
  const requested = browsers ?? [];
  const named = requested.length > 0;
  const families = new Set<BrowserFamily>(
    !named || requested.includes('all') ? BROWSER_FAMILIES : requested.filter((b): b is BrowserFamily => b !== 'all'),
  );
  const picked = channels.filter((ch) => families.has(ch.family) && (exists(ch.userDataDir) || (named && ch.stable)));
  if (picked.length > 0) return picked;
  return channels.filter((ch) => ch.family === 'edge' && ch.stable);
}

/** Write (when changed) a file; returns whether it was written. */
function writeIfChanged(file: string, content: string, mode: number): boolean {
  let current: string | null = null;
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) {
    fs.chmodSync(file, mode);
    return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, { mode });
  fs.chmodSync(file, mode);
  return true;
}

/** The real `reg.exe` runner (Windows). */
export function defaultReg(args: string[]): string {
  return execFileSync('reg', args, { encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
}

interface Target {
  label: string;
  /** Manifest file (macOS / Linux / --manifest-dir), or the shared one in $REQLENS_HOME on Windows. */
  manifest: string;
  registryKey?: string;
}

function targetsFor(ctx: InstallContext, mode: 'install' | 'uninstall'): Target[] {
  if (ctx.manifestDir) {
    return [{ label: '--manifest-dir', manifest: path.join(path.resolve(ctx.manifestDir), manifestFileName()) }];
  }
  const channels = browserChannels(ctx.platform, ctx.homedir, ctx.env);
  const chosen =
    mode === 'install'
      ? selectChannels(channels, ctx.browsers, (dir) => fs.existsSync(dir))
      : channels.filter((ch) => !ctx.browsers?.length || ctx.browsers.includes('all') || ctx.browsers.includes(ch.family));
  return chosen.map((ch) => ({
    label: ch.name,
    manifest: ch.manifestDir ? path.join(ch.manifestDir, manifestFileName()) : homeManifestPath(ctx.home),
    registryKey: ch.registryKey,
  }));
}

/** Every manifest a previous install may have written (ids are kept from all of them). */
function knownManifests(ctx: InstallContext): string[] {
  if (ctx.manifestDir) return [];
  const files = browserChannels(ctx.platform, ctx.homedir, ctx.env)
    .map((ch) => (ch.manifestDir ? path.join(ch.manifestDir, manifestFileName()) : null))
    .filter((file): file is string => file !== null);
  return [...files, homeManifestPath(ctx.home)];
}

/** Install (or refresh) the launcher and manifests. Throws InstallError for user errors. */
export function install(options: InstallOptions): InstallResult {
  const ids: string[] = [];
  for (const raw of options.extensionIds) {
    const id = normalizeExtensionId(raw);
    if (!id) throw new InstallError(`Invalid extension id "${raw}": expected 32 letters a–p (shown in kineReqLens Settings → Claude Code).`);
    ids.push(id);
  }
  const home = path.resolve(options.home);
  const ctx = { ...options, home };
  const problem = socketPathProblem(hubSocketPath(home, ctx.platform), ctx.platform);
  if (problem) throw new InstallError(problem);
  const targets = targetsFor(ctx, 'install');
  const known = unique([...targets.map((target) => target.manifest), ...knownManifests(ctx)]);
  const allIds = unique([...known.flatMap((file) => readManifestIds(file)), ...ids]);
  if (allIds.length === 0) throw new InstallError(MISSING_ID_MESSAGE);

  fs.mkdirSync(home, { recursive: true, mode: 0o700 });
  const launcher = launcherPath(home, ctx.platform);
  const launcherChanged = writeIfChanged(launcher, launcherScript(ctx.nodePath, ctx.scriptPath, home, ctx.platform), 0o755);
  ctx.out(`${launcherChanged ? 'Wrote' : 'Up to date'}: launcher ${launcher}`);

  const content = `${JSON.stringify(buildManifest(launcher, allIds), null, 2)}\n`;
  const manifests: string[] = [];
  const registryKeys: string[] = [];
  for (const target of targets) {
    if (!manifests.includes(target.manifest)) {
      const changed = writeIfChanged(target.manifest, content, 0o644);
      manifests.push(target.manifest);
      ctx.out(`${changed ? 'Wrote' : 'Up to date'}: ${target.label} manifest ${target.manifest}`);
    }
    if (target.registryKey) {
      (ctx.runReg ?? defaultReg)(['add', target.registryKey, '/ve', '/t', 'REG_SZ', '/d', target.manifest, '/f']);
      registryKeys.push(target.registryKey);
      ctx.out(`Registered: ${target.registryKey}`);
    }
  }
  ctx.out(`Allowed extension ids: ${allIds.join(', ')}`);
  printNextSteps(ctx);
  return { launcher, manifests, registryKeys, extensionIds: allIds };
}

function printNextSteps(ctx: InstallContext): void {
  const server = `"${ctx.nodePath}" "${ctx.scriptPath}"`;
  ctx.out('');
  ctx.out('Next steps:');
  ctx.out('  1. Register the MCP server with Claude Code (once):');
  ctx.out(`       claude mcp add --scope user reqlens -- ${server}`);
  ctx.out('  2. In the browser: kineReqLens overlay → Settings → Claude Code → Enable.');
  ctx.out('  3. Optional: let "Send to Claude Code" items arrive in the conversation (channels research preview):');
  ctx.out('       claude --dangerously-load-development-channels server:reqlens');
  ctx.out(`  Check the setup any time: ${server} doctor`);
}

export interface UninstallResult {
  removed: string[];
  registryKeys: string[];
}

/** Remove manifests (and registry keys) for the selected browsers plus the launcher. */
export function uninstall(ctx: InstallContext): UninstallResult {
  const home = path.resolve(ctx.home);
  const removed: string[] = [];
  const registryKeys: string[] = [];
  for (const target of targetsFor({ ...ctx, home }, 'uninstall')) {
    if (target.registryKey) {
      try {
        (ctx.runReg ?? defaultReg)(['delete', target.registryKey, '/f']);
        registryKeys.push(target.registryKey);
        ctx.out(`Removed: ${target.registryKey}`);
      } catch {
        // Key absent: nothing to remove.
      }
    }
    if (!removed.includes(target.manifest) && fs.existsSync(target.manifest)) {
      fs.rmSync(target.manifest, { force: true });
      removed.push(target.manifest);
      ctx.out(`Removed: ${target.label} manifest ${target.manifest}`);
    }
  }
  const launcher = launcherPath(home, ctx.platform);
  if (fs.existsSync(launcher)) {
    fs.rmSync(launcher, { force: true });
    removed.push(launcher);
    ctx.out(`Removed: launcher ${launcher}`);
  }
  if (removed.length === 0 && registryKeys.length === 0) ctx.out('Nothing to remove.');
  else ctx.out('Also remove the MCP server from Claude Code if you added it:  claude mcp remove --scope user reqlens');
  return { removed, registryKeys };
}

function unique(values: string[]): string[] {
  return [...new Set(values)];
}
